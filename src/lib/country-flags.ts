export function getCountryFlagUrl(teamName: string): string | null {
  // Direct match
  const code = COUNTRY_CODES[teamName];
  if (code) return `https://flagcdn.com/w80/${code}.webp`;

  // Try stripping common suffixes like "U23", "U21", "U19", "U20"
  const stripped = teamName.replace(/\s+U\d+$/i, "").trim();
  const strippedCode = COUNTRY_CODES[stripped];
  if (strippedCode) return `https://flagcdn.com/w80/${strippedCode}.webp`;

  return null;
}
